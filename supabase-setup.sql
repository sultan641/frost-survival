-- Frost Survival setup: review and run in Supabase SQL Editor.
-- IMPORTANT: This starter SQL opens public INSERT only for application/bug submissions.
-- Admin SELECT/UPDATE/DELETE requires an authenticated admin UID allowlist.
-- Replace YOUR_SUPABASE_AUTH_USER_UUID with the UUID from Authentication > Users.
-- Do not put a service_role/secret key in any website file.

create table if not exists public.announcements (
  id bigint generated by default as identity primary key,
  game_name text not null,
  title text not null,
  message text not null,
  created_at timestamptz not null default now()
);
alter table public.announcements enable row level security;
grant select on public.announcements to anon, authenticated;
grant insert, update, delete, select on public.announcements to authenticated;
drop policy if exists "Public can read announcements" on public.announcements;
create policy "Public can read announcements" on public.announcements for select to anon, authenticated using (true);

create table if not exists public.team_applications (
  id bigint generated by default as identity primary key,
  name text not null,
  discord_username text not null,
  role text not null,
  channel_url text,
  livestream text,
  experience text,
  message text not null,
  created_at timestamptz not null default now()
);
alter table public.team_applications enable row level security;
revoke all on public.team_applications from anon, authenticated;
grant insert on public.team_applications to anon, authenticated;
grant select, delete on public.team_applications to authenticated;
drop policy if exists "Public can submit applications" on public.team_applications;
create policy "Public can submit applications" on public.team_applications for insert to anon, authenticated with check (length(name) between 1 and 100 and length(message) between 1 and 3000);
drop policy if exists "Admin can read applications" on public.team_applications;
create policy "Admin can read applications" on public.team_applications for select to authenticated using ((select auth.uid()) = 'YOUR_SUPABASE_AUTH_USER_UUID'::uuid);
drop policy if exists "Admin can delete applications" on public.team_applications;
create policy "Admin can delete applications" on public.team_applications for delete to authenticated using ((select auth.uid()) = 'YOUR_SUPABASE_AUTH_USER_UUID'::uuid);

create table if not exists public.bug_reports (
  id bigint generated by default as identity primary key,
  name text not null,
  game_name text not null,
  bug_location text not null,
  description text not null,
  suggested_solution text,
  improvement_ideas text,
  screenshot_url text,
  created_at timestamptz not null default now()
);
alter table public.bug_reports enable row level security;
revoke all on public.bug_reports from anon, authenticated;
grant insert on public.bug_reports to anon, authenticated;
grant select, delete on public.bug_reports to authenticated;
drop policy if exists "Public can submit bug reports" on public.bug_reports;
create policy "Public can submit bug reports" on public.bug_reports for insert to anon, authenticated with check (length(name) between 1 and 150 and length(description) between 1 and 4000);
drop policy if exists "Admin can read bug reports" on public.bug_reports;
create policy "Admin can read bug reports" on public.bug_reports for select to authenticated using ((select auth.uid()) = 'YOUR_SUPABASE_AUTH_USER_UUID'::uuid);
drop policy if exists "Admin can delete bug reports" on public.bug_reports;
create policy "Admin can delete bug reports" on public.bug_reports for delete to authenticated using ((select auth.uid()) = 'YOUR_SUPABASE_AUTH_USER_UUID'::uuid);

-- Existing gift_codes table: ensure RLS is enabled and public reads are limited to active codes.
alter table public.gift_codes enable row level security;
grant select on public.gift_codes to anon, authenticated;
grant insert, update, delete, select on public.gift_codes to authenticated;
drop policy if exists "Public read active gift codes" on public.gift_codes;
create policy "Public read active gift codes" on public.gift_codes for select to anon, authenticated using (active = true);
drop policy if exists "Admin manages gift codes" on public.gift_codes;
create policy "Admin manages gift codes" on public.gift_codes for all to authenticated using ((select auth.uid()) = 'YOUR_SUPABASE_AUTH_USER_UUID'::uuid) with check ((select auth.uid()) = 'YOUR_SUPABASE_AUTH_USER_UUID'::uuid);

-- Existing announcements: restrict writes to the admin account.
drop policy if exists "Admin manages announcements" on public.announcements;
create policy "Admin manages announcements" on public.announcements for all to authenticated using ((select auth.uid()) = 'YOUR_SUPABASE_AUTH_USER_UUID'::uuid) with check ((select auth.uid()) = 'YOUR_SUPABASE_AUTH_USER_UUID'::uuid);

