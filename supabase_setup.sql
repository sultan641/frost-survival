-- Frost Survival website admin database setup
-- Run in Supabase Dashboard > SQL Editor.
create table if not exists public.site_admins (
 user_id uuid primary key references auth.users(id) on delete cascade
);
create table if not exists public.site_content (
 version_id text primary key check (version_id in ('wos-v4','v5-europe','v5-china','kingshot-v4')),
 content jsonb not null default '{}'::jsonb,
 updated_at timestamptz not null default now()
);
create table if not exists public.gift_codes (
 id bigint generated by default as identity primary key,
 version_id text not null check (version_id in ('wos-v4','v5-europe','v5-china','kingshot-v4')),
 code text not null,
 created_at timestamptz not null default now(),
 unique(version_id, code)
);
alter table public.site_admins enable row level security;
alter table public.site_content enable row level security;
alter table public.gift_codes enable row level security;
create policy "admins can read own admin row" on public.site_admins for select to authenticated using (user_id = auth.uid());
create policy "public can read site content" on public.site_content for select using (true);
create policy "admins can insert content" on public.site_content for insert to authenticated with check (exists(select 1 from public.site_admins a where a.user_id=auth.uid()));
create policy "admins can update content" on public.site_content for update to authenticated using (exists(select 1 from public.site_admins a where a.user_id=auth.uid())) with check (exists(select 1 from public.site_admins a where a.user_id=auth.uid()));
create policy "public can read gift codes" on public.gift_codes for select using (true);
create policy "admins can insert gift codes" on public.gift_codes for insert to authenticated with check (exists(select 1 from public.site_admins a where a.user_id=auth.uid()));
create policy "admins can delete gift codes" on public.gift_codes for delete to authenticated using (exists(select 1 from public.site_admins a where a.user_id=auth.uid()));
