-- Run this in Supabase Dashboard > SQL Editor.
create table if not exists public.gift_codes (
  id bigint generated by default as identity primary key,
  code text not null unique,
  created_at timestamptz not null default now()
);
create table if not exists public.gift_code_admins (
  user_id uuid primary key references auth.users(id) on delete cascade
);
alter table public.gift_codes enable row level security;
alter table public.gift_code_admins enable row level security;
-- Everyone can read gift codes; only listed admin users can add/remove codes.
create policy "Anyone can read gift codes" on public.gift_codes for select using (true);
create policy "Admins can insert gift codes" on public.gift_codes for insert to authenticated with check (exists (select 1 from public.gift_code_admins a where a.user_id = auth.uid()));
create policy "Admins can delete gift codes" on public.gift_codes for delete to authenticated using (exists (select 1 from public.gift_code_admins a where a.user_id = auth.uid()));
create policy "Admins can read own admin row" on public.gift_code_admins for select to authenticated using (user_id = auth.uid());
